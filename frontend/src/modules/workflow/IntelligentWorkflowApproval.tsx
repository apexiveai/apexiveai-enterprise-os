import { useCallback, useEffect, useState } from 'react'
import { apiUrl } from '../../lib/api'
import {
  AlertTriangle,
  ArrowUpRight,
  Check,
  CheckCircle2,
  Clock3,
  FileCheck2,
  GitBranch,
  ListChecks,
  LoaderCircle,
  RefreshCw,
  Send,
  ShieldCheck,
  UserRound,
  Users,
  Workflow,
} from 'lucide-react'

type WorkflowTask = {
  task_id: string
  execution_id: string
  name: string
  assignee: string
  status: 'pending' | 'completed'
  decision?: string
}

const capabilities = [
  { title: 'Multi-level Approval', detail: 'Route decisions through role-based approval levels.', icon: Users },
  { title: 'Conditional Workflow', detail: 'Branch workflow steps using business rules.', icon: GitBranch },
  { title: 'SLA Management', detail: 'Track due times and monitor service targets.', icon: Clock3 },
  { title: 'Escalation Rules', detail: 'Escalate overdue tasks to the right owner.', icon: AlertTriangle },
  { title: 'Human-in-the-Loop', detail: 'Include human review at critical AI decision points.', icon: UserRound },
  { title: 'E-Signature Integration', detail: 'Add signature steps to approval workflows.', icon: FileCheck2 },
  { title: 'Task Delegation', detail: 'Assign or delegate work to an authorized teammate.', icon: Send },
  { title: 'Process Analytics', detail: 'Measure approval time, backlog, and process outcomes.', icon: ListChecks },
]

async function responseError(response: Response) {
  try {
    const body = await response.json() as { detail?: unknown }
    if (typeof body.detail === 'string') return body.detail
    return response.statusText || `Request failed (${response.status}).`
  } catch {
    return response.statusText || `Request failed (${response.status}).`
  }
}

export default function IntelligentWorkflowApproval({ onNavigate }: { onNavigate: (label: string) => void }) {
  const [tasks, setTasks] = useState<WorkflowTask[]>([])
  const [loading, setLoading] = useState(true)
  const [workingTask, setWorkingTask] = useState('')
  const [error, setError] = useState('')
  const [notice, setNotice] = useState('')

  const loadTasks = useCallback(async () => {
    setLoading(true)
    setError('')
    try {
      const response = await fetch(apiUrl('/api/v1/workflow/tasks'))
      if (!response.ok) throw new Error(await responseError(response))
      setTasks(await response.json() as WorkflowTask[])
    } catch (loadError) {
      setError(loadError instanceof Error ? loadError.message : 'Could not load workflow tasks.')
    } finally {
      setLoading(false)
    }
  }, [])

  useEffect(() => {
    let active = true
    fetch(apiUrl('/api/v1/workflow/tasks'))
      .then(async (response) => {
        if (!response.ok) throw new Error(await responseError(response))
        return await response.json() as WorkflowTask[]
      })
      .then((items) => {
        if (active) setTasks(items)
      })
      .catch((loadError: unknown) => {
        if (active) setError(loadError instanceof Error ? loadError.message : 'Could not load workflow tasks.')
      })
      .finally(() => {
        if (active) setLoading(false)
      })
    return () => { active = false }
  }, [])

  const decide = async (task: WorkflowTask, decision: 'approved' | 'changes_requested') => {
    setWorkingTask(task.task_id)
    setError('')
    setNotice('')
    try {
      const query = new URLSearchParams({ decision })
      const response = await fetch(
        apiUrl(`/api/v1/workflow/tasks/${encodeURIComponent(task.task_id)}/complete?${query}`),
        { method: 'POST' },
      )
      if (!response.ok) throw new Error(await responseError(response))
      const updated = await response.json() as WorkflowTask
      setTasks((current) => current.map((item) => item.task_id === updated.task_id ? updated : item))
      setNotice(`${task.name}: ${decision.replaceAll('_', ' ')} saved.`)
    } catch (actionError) {
      setError(actionError instanceof Error ? actionError.message : 'Could not update workflow task.')
    } finally {
      setWorkingTask('')
    }
  }

  const pendingTasks = tasks.filter((task) => task.status === 'pending')

  return (
    <div className="workflow-approval-page">
      {notice && <div className="workflow-approval-notice" role="status"><CheckCircle2 size={14} />{notice}</div>}
      {error && <div className="workflow-approval-notice" role="alert">{error}</div>}
      <header className="workflow-approval-header">
        <div>
          <span className="workflow-approval-eyebrow"><Workflow size={13} /> HUMAN + AI PROCESS CONTROL</span>
          <h1>Intelligent Workflow &amp; Approval</h1>
          <p>Review and decide on human tasks generated by saved workflow runs.</p>
        </div>
        <div className="workflow-approval-actions">
          <button onClick={() => void loadTasks()} disabled={loading}>
            {loading ? <LoaderCircle size={13} /> : <RefreshCw size={13} />} Refresh inbox
          </button>
          <button onClick={() => onNavigate('Workflow Studio')}>Open Workflow Studio <ArrowUpRight size={13} /></button>
        </div>
      </header>

      <section className="workflow-approval-metrics" aria-label="Workflow approval overview">
        <article><span><ListChecks size={14} /> Pending Approvals</span><strong>{pendingTasks.length}</strong><em>From persisted workflow tasks</em></article>
        <article><span><CheckCircle2 size={14} /> Completed Tasks</span><strong>{tasks.length - pendingTasks.length}</strong><em>Decisions saved by the backend</em></article>
        <article><span><Workflow size={14} /> Workflow Tasks</span><strong>{tasks.length}</strong><em>Loaded from the workflow API</em></article>
        <article><span><Clock3 size={14} /> Service status</span><strong>{loading ? 'Loading' : error ? 'Error' : 'Connected'}</strong><em>GET /api/v1/workflow/tasks</em></article>
      </section>

      <div className="workflow-approval-workspace">
        <section className="workflow-approval-panel workflow-approval-queue">
          <div className="workflow-approval-panel-heading">
            <div><h2>Approval Inbox</h2><p>Actions update the saved workflow task.</p></div>
            <span>{pendingTasks.length} pending</span>
          </div>
          <div className="workflow-approval-task-list">
            {pendingTasks.map((task) => (
              <article key={task.task_id}>
                <div className="workflow-approval-task-main">
                  <span className="workflow-approval-task-icon"><FileCheck2 size={15} /></span>
                  <div>
                    <small>{task.task_id} · Execution {task.execution_id}</small>
                    <strong>{task.name}</strong>
                    <span>Assigned to {task.assignee}</span>
                  </div>
                </div>
                <div className="workflow-approval-task-meta">
                  <span className="workflow-approval-result">Pending</span>
                  <div className="workflow-approval-task-actions">
                    <button className="request-changes" disabled={workingTask === task.task_id} onClick={() => void decide(task, 'changes_requested')}>Request changes</button>
                    <button className="approve" disabled={workingTask === task.task_id} onClick={() => void decide(task, 'approved')}>
                      {workingTask === task.task_id ? <LoaderCircle size={13} /> : <Check size={13} />} Approve
                    </button>
                  </div>
                </div>
              </article>
            ))}
            {!loading && pendingTasks.length === 0 && (
              <div className="inbox-empty">
                <CheckCircle2 size={22} />
                <strong>No pending tasks</strong>
                <span>Run a workflow containing a User task to add an approval here.</span>
              </div>
            )}
          </div>
          <button className="workflow-approval-view-all" onClick={() => onNavigate('Workflow Studio')}>Manage workflows <ArrowUpRight size={12} /></button>
        </section>

        <aside className="workflow-approval-panel workflow-approval-routing">
          <div className="workflow-approval-panel-heading">
            <div><h2>Workflow task lifecycle</h2><p>Persisted by the backend workflow service</p></div>
            <ShieldCheck size={15} />
          </div>
          <div className="workflow-approval-route">
            <div className="complete"><span><Check size={12} /></span><div><strong>Workflow run started</strong><small>Execution recorded by API</small></div></div>
            <i />
            <div className="current"><span>2</span><div><strong>User task created</strong><small>Waiting for a human decision</small></div></div>
            <i />
            <div className="upcoming"><span>3</span><div><strong>Decision submitted</strong><small>Approval or changes saved to task</small></div></div>
          </div>
          <div className="workflow-approval-rule"><AlertTriangle size={13} /><span><strong>Note</strong> This workflow runtime records tasks and decisions; it does not connect to ERP or execute business actions.</span></div>
        </aside>
      </div>

      <section className="workflow-approval-capabilities">
        <div className="workflow-approval-section-heading">
          <div><h2>Workflow &amp; Approval Controls</h2><p>Capability areas for governed, human-centered automation.</p></div>
          <span>8 CAPABILITIES</span>
        </div>
        <div className="workflow-approval-capability-grid">
          {capabilities.map(({ title, detail, icon: Icon }, index) => (
            <article key={title}>
              <span className="workflow-approval-capability-icon"><Icon size={15} /></span>
              <div><small>0{index + 1}</small><h3>{title}</h3><p>{detail}</p></div>
            </article>
          ))}
        </div>
      </section>
      <div className="workflow-approval-footnote"><ShieldCheck size={13} /> Approval and request-change decisions are persisted by the workflow API.</div>
    </div>
  )
}
